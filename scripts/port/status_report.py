"""Write PORTING_STATUS.md from .lake/compile-results.json."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
r = json.load(open(os.path.join(ROOT, '.lake/compile-results.json')))
log = lambda m: open(os.path.join(ROOT, '.lake/compile-logs', m + '.log')).read()
deps = {m: [i for i in re.findall(r'^import (\S+)', open(os.path.join(ROOT, *m.split('.')) + '.lean').read(), re.M) if i in r] for m in r}
rev = {}
for m, ds in deps.items():
    for d in ds: rev.setdefault(d, set()).add(m)
def desc(m):
    s, st = set(), [m]
    while st:
        for y in rev.get(st.pop(), ()):
            if y not in s: s.add(y); st.append(y)
    return s
blocked = sorted(m for m in r if 'does not exist' in log(m))
clean = sorted(m for m, v in r.items() if v['errors'] == 0 and v['sorry_warnings'] == 0)
own = sorted((m for m in r if m not in blocked and m not in clean), key=lambda m: (-len(desc(m)), m))
meta = sorted({os.path.relpath(os.path.join(rt, f), ROOT) for rt, _, fs in os.walk(os.path.join(ROOT, 'LiquidTensorExperiment'))
               for f in fs if f.endswith('.lean') and re.search(r'unsafe def|run_tac', open(os.path.join(rt, f)).read())})
L = [f"# Porting status\n",
     f"Generated by `scripts/port/status_report.py` from a full dependency-ordered compile of all "
     f"{len(r)} modules (403 LTE modules + `Compat.AdditiveCategory`) against mathlib4 `79254c9790`.\n",
     "| Status | Modules |", "|---|---|",
     f"| ✅ Compiles (no errors, no `sorry`) | {len(clean)} |",
     f"| ❌ Has its own compile errors | {len(own)} ({sum(r[m]['errors'] for m in own)} errors) |",
     f"| ⏸ Not yet checked: an import does not compile | {len(blocked)} |", "",
     "A module counted as compiling is checked by Lean 4 itself; `declaration uses 'sorry'` warnings would disqualify it (there are none).\n",
     "## ✅ Modules that compile\n"] + [f"- `{m}`" for m in clean] + [
     "\n## ❌ Modules with their own errors\n",
     "Ordered by how many modules (transitively) wait on them.\n",
     "| Module | Errors | Modules blocked behind it |", "|---|---:|---:|"] + [
     f"| `{m}` | {r[m]['errors']} | {len(desc(m))} |" for m in own] + [
     "\n## Files still containing untranslated Lean 3 metaprograms\n",
     "mathport cannot translate Lean 3 `meta` code (tactic definitions); it emits `unsafe def … := sorry` / `run_tac`. "
     "These must be rewritten as Lean 4 tactics (done so far: `hom_tac`, `aux_tac`, `fact_arith`).\n"] + [f"- `{p}`" for p in meta] + [""]
open(os.path.join(ROOT, 'PORTING_STATUS.md'), 'w').write('\n'.join(L))
print(len(clean), len(own), len(blocked), len(meta))
